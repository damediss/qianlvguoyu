-- 知识点鉴定范围 4 级树 (L0~L3)
CREATE TABLE IF NOT EXISTS exam_knowledge_structure (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  type INT NOT NULL DEFAULT 0 COMMENT '类型: 0=理论, 1=实操',
  use_type INT NULL DEFAULT NULL COMMENT '用途类型',
  course_id INT NULL DEFAULT NULL COMMENT '科目ID → exam_course.id',
  parent_id INT NULL DEFAULT 0 COMMENT '父级ID, 0=根',
  cover VARCHAR(500) NULL COMMENT '封面',
  intro VARCHAR(1000) NULL COMMENT '简介',
  title VARCHAR(255) NOT NULL COMMENT '名称',
  series_no VARCHAR(200) NULL COMMENT '编号',
  level INT NOT NULL DEFAULT 0 COMMENT '层级: 0=一级鉴定范围, 1=二级, 2=三级, 3=鉴定点',
  important INT NULL DEFAULT 0 COMMENT '重要程度',
  user_id INT NULL COMMENT '创建人ID',
  status INT NOT NULL DEFAULT 1 COMMENT '状态: 0=停用, 1=启用',
  sort_number INT NOT NULL DEFAULT 1 COMMENT '排序号',
  tenant_id INT NOT NULL COMMENT '租户ID',
  org_id INT NULL COMMENT '组织ID',
  org_name VARCHAR(255) NULL COMMENT '组织名称',
  amount INT NULL DEFAULT 0 COMMENT '关联试题数量',
  create_time DATETIME NULL COMMENT '创建时间',
  deleted INT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
  INDEX idx_ks_tenant (tenant_id),
  INDEX idx_ks_course (tenant_id, course_id),
  INDEX idx_ks_parent (tenant_id, parent_id),
  INDEX idx_ks_level (tenant_id, course_id, level)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='鉴定知识点(4级树)';

-- 试题详情
CREATE TABLE IF NOT EXISTS exam_exam_detail (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  exam_id INT NULL COMMENT '考试ID(可为空表示题库中的题)',
  task_detail_id INT NULL COMMENT '任务明细ID',
  source INT NULL DEFAULT 0 COMMENT '来源: 0=手工, 1=导入',
  org_id INT NULL COMMENT '组织ID',
  org_name VARCHAR(255) NULL COMMENT '组织名称',
  knowledge_id INT NULL COMMENT '知识点ID → exam_knowledge_structure.id',
  is_private INT NULL DEFAULT 0 COMMENT '是否私有: 0=否, 1=是',
  difficulty INT NULL DEFAULT 2 COMMENT '难度: 0=易, 1=较易, 2=中, 3=较难, 4=难',
  user_id INT NULL COMMENT '创建人',
  check_user_id INT NULL COMMENT '初审人',
  final_check_user_id INT NULL COMMENT '终审人',
  type VARCHAR(50) NULL COMMENT '题型: single/multi/judge/essay/explain/cal/simple_fill/fill/answer等',
  keyword VARCHAR(500) NULL COMMENT '关键词',
  audio VARCHAR(500) NULL COMMENT '音频路径',
  video VARCHAR(500) NULL COMMENT '视频路径',
  content TEXT NULL COMMENT '题干',
  answer TEXT NULL COMMENT '答案(JSON)',
  score DECIMAL(8,2) NULL COMMENT '分值',
  resolve TEXT NULL COMMENT '解析',
  check_status INT NULL DEFAULT 0 COMMENT '初审状态: 0=待审, 1=通过, 2=不通过',
  final_check_status INT NULL DEFAULT 0 COMMENT '终审状态: 0=待审, 1=通过, 2=不通过',
  status INT NOT NULL DEFAULT 1 COMMENT '状态: 0=无效, 1=有效',
  sort_number INT NOT NULL DEFAULT 1 COMMENT '排序号',
  tenant_id INT NOT NULL COMMENT '租户ID',
  create_time DATETIME NULL COMMENT '创建时间',
  check_time DATETIME NULL COMMENT '审核时间',
  final_check_time DATETIME NULL COMMENT '终审时间',
  deleted INT NOT NULL DEFAULT 0 COMMENT '逻辑删除',
  INDEX idx_ed_tenant (tenant_id),
  INDEX idx_ed_knowledge (tenant_id, knowledge_id),
  INDEX idx_ed_type (tenant_id, type),
  INDEX idx_ed_status (tenant_id, status),
  INDEX idx_ed_difficulty (tenant_id, difficulty)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='试题详情';
