CREATE TABLE IF NOT EXISTS certification_defense_score (
  id BIGINT NOT NULL,
  tenant_id BIGINT NOT NULL,
  task_id BIGINT NOT NULL COMMENT '认定任务id',
  candidate_id BIGINT NOT NULL COMMENT '考生id',
  report_id BIGINT NULL COMMENT '业绩评估报告id',
  assessor_id BIGINT NOT NULL COMMENT '考评员档案id',
  assessor_user_id BIGINT NOT NULL COMMENT '考评员登录用户id',
  sheet_type VARCHAR(40) NOT NULL COMMENT 'THESIS/PERFORMANCE',
  status VARCHAR(40) NOT NULL DEFAULT 'draft' COMMENT 'draft/submitted',
  payload_json LONGTEXT NOT NULL COMMENT '评分表内容JSON',
  content_subtotal DECIMAL(10, 2) NULL COMMENT '论文内容部分小计(100分制)',
  defense_subtotal DECIMAL(10, 2) NULL COMMENT '论文答辩部分小计(100分制)',
  raw_total DECIMAL(10, 2) NULL COMMENT '业绩评估合计(100分制)',
  final_score DECIMAL(10, 2) NULL COMMENT '最终得分',
  rejected INT NOT NULL DEFAULT 0 COMMENT '否定项是否成立 0/1',
  signature_file_id BIGINT NULL COMMENT '评审专家电子签名文件id',
  signature_hash VARCHAR(128) NULL COMMENT '签名文件hash',
  submitted_at DATETIME NULL COMMENT '提交时间',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by BIGINT NULL,
  updated_by BIGINT NULL,
  deleted INT NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY uk_cert_defense_score (tenant_id, task_id, candidate_id, assessor_id, sheet_type, deleted),
  KEY idx_cert_defense_score_report (tenant_id, report_id, deleted),
  KEY idx_cert_defense_score_assessor (tenant_id, assessor_id, task_id, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='综合答辩评分表';
