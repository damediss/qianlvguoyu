CREATE TABLE IF NOT EXISTS exam_task_ximu (
  id INT NOT NULL AUTO_INCREMENT,
  work_type_id INT NOT NULL COMMENT '工种ID',
  level INT NOT NULL COMMENT '等级 5初级工 4中级工 3高级工 2技师 1高级技师',
  types TINYINT NOT NULL DEFAULT 0 COMMENT '类型 0理论 1实操',
  nums INT NOT NULL DEFAULT 0 COMMENT '题目总数',
  status TINYINT NOT NULL DEFAULT 0 COMMENT '状态 0待审核 1初审审核中 2终审审核中 3完成',
  expert_start INT NULL COMMENT '初审专家ID',
  expert_end INT NULL COMMENT '终审专家ID',
  file_path VARCHAR(500) NULL COMMENT '上传文件路径',
  addtime BIGINT NOT NULL DEFAULT 0 COMMENT '创建时间戳',
  tenant_id INT NOT NULL DEFAULT 1 COMMENT '租户ID',
  deleted TINYINT NOT NULL DEFAULT 0 COMMENT '是否删除 0否 1是',
  create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  created_by INT NULL COMMENT '创建人',
  updated_by INT NULL COMMENT '更新人',
  PRIMARY KEY (id),
  INDEX idx_tenant_id (tenant_id),
  INDEX idx_work_type_id (work_type_id),
  INDEX idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='细目表任务';

