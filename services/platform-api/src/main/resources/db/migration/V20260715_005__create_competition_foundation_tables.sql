-- FND-01: competition foundation tables only.
CREATE TABLE competition_event (
  id BIGINT NOT NULL PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  name VARCHAR(128) NOT NULL,
  code VARCHAR(64) NOT NULL,
  scope VARCHAR(32) NOT NULL,
  owner_org_id BIGINT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'draft',
  registration_audit_required TINYINT NOT NULL DEFAULT 0,
  start_at DATETIME NULL,
  end_at DATETIME NULL,
  description VARCHAR(2000) NULL,
  created_by BIGINT NULL,
  created_at DATETIME NOT NULL,
  updated_by BIGINT NULL,
  updated_at DATETIME NOT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  CONSTRAINT chk_competition_event_scope CHECK (scope IN ('platform', 'enterprise_internal')),
  CONSTRAINT chk_competition_event_status CHECK (status IN ('draft', 'published', 'closed', 'archived')),
  CONSTRAINT chk_competition_event_owner CHECK (scope <> 'enterprise_internal' OR owner_org_id IS NOT NULL),
  KEY idx_competition_event_scope_status (tenant_id, scope, status, deleted),
  KEY idx_competition_event_owner_status (tenant_id, owner_org_id, status, deleted),
  UNIQUE KEY uk_competition_event_code (tenant_id, code, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='竞赛赛事基础信息';

CREATE TABLE competition_event_org (
  id BIGINT NOT NULL PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  event_id BIGINT NOT NULL,
  org_id BIGINT NOT NULL,
  quota INT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'invited',
  import_permission TINYINT NOT NULL DEFAULT 0,
  created_by BIGINT NULL,
  created_at DATETIME NOT NULL,
  updated_by BIGINT NULL,
  updated_at DATETIME NOT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  CONSTRAINT chk_competition_event_org_status CHECK (status IN ('invited', 'active', 'suspended', 'closed')),
  CONSTRAINT chk_competition_event_org_quota CHECK (quota IS NULL OR quota >= 0),
  KEY idx_competition_event_org_org_status (tenant_id, org_id, status, deleted),
  UNIQUE KEY uk_competition_event_org (tenant_id, event_id, org_id, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='竞赛参与企业关系';

CREATE TABLE competition_stage (
  id BIGINT NOT NULL PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  event_id BIGINT NOT NULL,
  name VARCHAR(128) NOT NULL,
  stage_type VARCHAR(32) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  start_at DATETIME NULL,
  end_at DATETIME NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'draft',
  description VARCHAR(2000) NULL,
  created_by BIGINT NULL,
  created_at DATETIME NOT NULL,
  updated_by BIGINT NULL,
  updated_at DATETIME NOT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  CONSTRAINT chk_competition_stage_sort_order CHECK (sort_order >= 0),
  KEY idx_competition_stage_order (tenant_id, event_id, sort_order, deleted),
  KEY idx_competition_stage_status (tenant_id, event_id, status, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='竞赛赛段';

CREATE TABLE competition_task_template (
  id BIGINT NOT NULL PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  stage_id BIGINT NOT NULL,
  task_type VARCHAR(32) NOT NULL,
  title VARCHAR(128) NOT NULL,
  description VARCHAR(2000) NULL,
  completion_rule VARCHAR(2000) NULL,
  requires_review TINYINT NOT NULL DEFAULT 0,
  deadline_rule VARCHAR(512) NULL,
  allowed_file_types VARCHAR(512) NULL,
  sort_order INT NOT NULL DEFAULT 0,
  status VARCHAR(32) NOT NULL DEFAULT 'draft',
  created_by BIGINT NULL,
  created_at DATETIME NOT NULL,
  updated_by BIGINT NULL,
  updated_at DATETIME NOT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  CONSTRAINT chk_competition_task_template_type CHECK (task_type IN ('notice_ack', 'check_in', 'file_submission')),
  CONSTRAINT chk_competition_task_template_sort_order CHECK (sort_order >= 0),
  KEY idx_competition_task_template_order (tenant_id, stage_id, sort_order, deleted),
  KEY idx_competition_task_template_status (tenant_id, stage_id, task_type, status, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='竞赛任务模板';

CREATE TABLE competition_roster_import (
  id BIGINT NOT NULL PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  event_id BIGINT NOT NULL,
  org_id BIGINT NOT NULL,
  batch_no VARCHAR(64) NOT NULL,
  source_file_id BIGINT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'validating',
  total_count INT NOT NULL DEFAULT 0,
  valid_count INT NOT NULL DEFAULT 0,
  invalid_count INT NOT NULL DEFAULT 0,
  confirmed_by BIGINT NULL,
  confirmed_at DATETIME NULL,
  summary VARCHAR(2000) NULL,
  created_by BIGINT NULL,
  created_at DATETIME NOT NULL,
  updated_by BIGINT NULL,
  updated_at DATETIME NOT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  CONSTRAINT chk_competition_roster_import_status CHECK (status IN ('validating', 'validation_failed', 'pending_confirm', 'confirmed')),
  KEY idx_competition_roster_import_event_org_status (tenant_id, event_id, org_id, status, deleted),
  UNIQUE KEY uk_competition_roster_import_batch_no (tenant_id, batch_no, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='竞赛名单导入批次';

CREATE TABLE competition_roster_item (
  id BIGINT NOT NULL PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  batch_id BIGINT NOT NULL,
  employee_no VARCHAR(64) NOT NULL,
  name VARCHAR(128) NOT NULL,
  work_type VARCHAR(64) NULL,
  level VARCHAR(32) NULL,
  validation_status VARCHAR(32) NOT NULL DEFAULT 'valid',
  error_message VARCHAR(512) NULL,
  created_by BIGINT NULL,
  created_at DATETIME NOT NULL,
  updated_by BIGINT NULL,
  updated_at DATETIME NOT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  CONSTRAINT chk_competition_roster_item_validation_status CHECK (validation_status IN ('valid', 'invalid')),
  KEY idx_competition_roster_item_validation (tenant_id, batch_id, validation_status, deleted),
  UNIQUE KEY uk_competition_roster_item_employee_no (tenant_id, batch_id, employee_no, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='竞赛名单导入行';

CREATE TABLE competition_registration (
  id BIGINT NOT NULL PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  event_id BIGINT NOT NULL,
  org_id BIGINT NOT NULL,
  roster_item_id BIGINT NOT NULL,
  source VARCHAR(32) NOT NULL DEFAULT 'enterprise_import',
  status VARCHAR(32) NOT NULL DEFAULT 'imported_pending_confirm',
  audit_reason VARCHAR(1000) NULL,
  audited_by BIGINT NULL,
  audited_at DATETIME NULL,
  created_by BIGINT NULL,
  created_at DATETIME NOT NULL,
  updated_by BIGINT NULL,
  updated_at DATETIME NOT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  CONSTRAINT chk_competition_registration_source CHECK (source = 'enterprise_import'),
  CONSTRAINT chk_competition_registration_status CHECK (status IN ('imported_pending_confirm', 'pending_audit', 'supplement_required', 'rejected', 'eligible_unactivated', 'withdrawn', 'expired')),
  KEY idx_competition_registration_event_org_status (tenant_id, event_id, org_id, status, deleted),
  UNIQUE KEY uk_competition_registration_roster_item (tenant_id, roster_item_id, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='竞赛参赛资格';

CREATE TABLE competition_notice (
  id BIGINT NOT NULL PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  event_id BIGINT NOT NULL,
  title VARCHAR(256) NOT NULL,
  content TEXT NOT NULL,
  version INT NOT NULL DEFAULT 1,
  status VARCHAR(32) NOT NULL DEFAULT 'draft',
  published_by BIGINT NULL,
  published_at DATETIME NULL,
  created_by BIGINT NULL,
  created_at DATETIME NOT NULL,
  updated_by BIGINT NULL,
  updated_at DATETIME NOT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  CONSTRAINT chk_competition_notice_status CHECK (status IN ('draft', 'published')),
  CONSTRAINT chk_competition_notice_version CHECK (version > 0),
  KEY idx_competition_notice_event_status (tenant_id, event_id, status, deleted),
  KEY idx_competition_notice_event_published_at (tenant_id, event_id, published_at, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='竞赛站内通知';

