  sno VARCHAR(100) NOT NULL COMMENT '编号',
  sno_0 JSON NULL COMMENT '一级编号 JSON',
  sno_1 JSON NULL COMMENT '二级编号 JSON',
  title VARCHAR(1000) NULL COMMENT '标题',
  sno_item VARCHAR(100) NULL COMMENT '细目编号',
  sno_title VARCHAR(2000) NULL COMMENT '细目内容',
  row_column VARCHAR(20) NULL COMMENT 'Excel单元格位置',
  tenant_id INT NOT NULL DEFAULT 1 COMMENT '租户ID',
  deleted TINYINT NOT NULL DEFAULT 0 COMMENT '是否删除 0否 1是',
  create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  created_by INT NULL COMMENT '创建人',
  updated_by INT NULL COMMENT '更新人',
  PRIMARY KEY (id),
  INDEX idx_task_id (task_id),
  INDEX idx_tenant_id (tenant_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='细目表明细';

